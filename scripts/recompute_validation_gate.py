"""Re-compute the cycle-zero validation gate under the locked composite (final drafting pass, 2026-10).

The committed tab_validation_gate.tex was produced from cycle-zero evaluation files whose
u_stored came from the legacy weighted-sum bootstrap composite (see
outputs/cycle_0/sweep_v2_1/README.md, finding 1). This script re-scores the held-out
cycle-zero validation fold (outputs/cycle_0/eval/<bench>_cycle0.json, 500 per benchmark)
with the locked composite (outputs/cycle_0/composite_calibration.json), applies the
four-outcome decision rule of caem/verification/verifier.py, and writes
outputs/analysis/validation_gate_locked.json and
defense/thesis_report/figures/auto/tab_validation_gate_locked.tex (validation gate and
per-benchmark diagnostics in one table).

Read-only on its inputs.
"""
import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from caem.verification.cal_prob_composite import CalProbComposite, COMPOSITE_SIGNALS  # noqa: E402

TRAIN = ("fever", "triviaqa", "commonsense_qa")
TRANSFER = ("truthfulqa", "strategyqa")
TAU_STORE, TAU_DEFER, PG_FLOOR, EE_U, EE_G = 0.60, 0.45, 0.20, 0.70, 0.20


def cohens_d(u, y):
    pos, neg = u[y == 1], u[y == 0]
    if len(pos) < 2 or len(neg) < 2:
        return float("nan")
    sp = math.sqrt(((len(pos) - 1) * pos.var(ddof=1) + (len(neg) - 1) * neg.var(ddof=1)) / (len(pos) + len(neg) - 2))
    return float((pos.mean() - neg.mean()) / sp)


def decide(u, r):
    if (r.get("u_internal") or 0) >= EE_U and (r.get("p_ground_max") or 0) <= EE_G:
        return "DISCARD"
    if u >= TAU_STORE:
        return "STORE"
    if u >= TAU_DEFER:
        return "DEFERRED"
    if (r.get("p_ground_max") or 0) < PG_FLOOR:
        return "ABSTAIN"
    return "DISCARD"


def label(r, b):
    if b == "truthfulqa" and r.get("em_llm_judged") is not None:
        return 1 if float(r["em_llm_judged"]) >= 1 else 0
    return 1 if (r.get("em") or 0) >= 1 else 0


def main():
    model = CalProbComposite.load(str(ROOT / "outputs/cycle_0/composite_calibration.json"))
    out = {"per_bench": {}}
    pooled = {"train": ([], []), "transfer": ([], [])}
    for b in TRAIN + TRANSFER:
        rows = json.load(open(ROOT / f"outputs/cycle_0/eval/{b}_cycle0.json"))["samples"]
        tag = b if b in TRAIN else None  # transfer benchmarks fall back to the pooled curves
        u = np.array([model.predict({k: r.get(k) for k in COMPOSITE_SIGNALS}, tag) for r in rows])
        y = np.array([label(r, b) for r in rows])
        dec = [decide(ui, r) for ui, r in zip(u, rows)]
        st = [i for i, d in enumerate(dec) if d == "STORE"]
        di = [i for i, d in enumerate(dec) if d == "DISCARD"]
        rec = {"n": len(rows), "em": float(y.mean()), "d": cohens_d(u, y), "stored": len(st),
               "precision": (float(y[st].mean()) if st else None),
               "poisoning": (float(1 - y[st].mean()) if st else None),
               "store_minus_discard": (float(u[st].mean() - u[di].mean()) if st and di else None),
               "decisions": {k: dec.count(k) for k in ("STORE", "DEFERRED", "ABSTAIN", "DISCARD")}}
        out["per_bench"][b] = rec
        grp = "train" if b in TRAIN else "transfer"
        pooled[grp][0].append(u)
        pooled[grp][1].append(y)
    for grp, (us, ys) in pooled.items():
        out[f"d_pooled_{grp}"] = cohens_d(np.concatenate(us), np.concatenate(ys))
    (ROOT / "outputs/analysis").mkdir(parents=True, exist_ok=True)
    json.dump(out, open(ROOT / "outputs/analysis/validation_gate_locked.json", "w"), indent=2)

    def f(x, sign=True):
        if x is None or (isinstance(x, float) and math.isnan(x)):
            return "--"
        return f"${x:+.2f}$" if sign else f"${x:.2f}$"
    P = out["per_bench"]
    names = {"fever": "FEVER", "triviaqa": "TriviaQA", "commonsense_qa": "CommonsenseQA",
             "truthfulqa": "TruthfulQA", "strategyqa": "StrategyQA"}
    # One table: benchmarks as rows, the registered checks as columns (thresholds in the header).
    lines = [
        "% Auto-generated by scripts/recompute_validation_gate.py (locked composite; final drafting pass 2026-10).",
        "\\begin{table}[!htbp]", "\\centering\\small",
        "\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule",
        "\\textbf{Benchmark} & \\textbf{EM} & \\twoline{Cohen's $d$\\\\($\\ge 0.20$)} & \\textbf{Stored} & "
        "\\twoline{Store minus\\\\discard ($\\ge 0.05$)} & \\twoline{Wrong among\\\\stored ($< 0.50$)} \\\\",
        "\\midrule",
        "\\multicolumn{6}{@{}l}{\\textit{Training panel (registered checks)}} \\\\",
    ]

    def row(b):
        r = P[b]
        return (f"{names[b]} & ${r['em']:.3f}$ & {f(r['d'])} & ${r['stored']}$ & "
                f"{f(r['store_minus_discard'])} & {f(r['poisoning'], False)} \\\\")
    lines += [row(b) for b in TRAIN]
    lines.append(f"Pooled & & {f(out['d_pooled_train'])} & ${sum(P[b]['stored'] for b in TRAIN)}$ & & \\\\")
    lines += ["\\midrule", "\\multicolumn{6}{@{}l}{\\textit{Transfer panel (diagnostic only)}} \\\\"]
    lines += [row(b) for b in TRANSFER]
    lines.append(f"Pooled & & {f(out['d_pooled_transfer'])} & ${sum(P[b]['stored'] for b in TRANSFER)}$ & & \\\\")
    lines += [
        "\\bottomrule", "\\end{tabular}",
        "\\caption[Cycle-zero validation gate under the locked composite.]{Cycle-zero validation gate re-scored with the locked composite on the held-out validation fold ($500$ questions per benchmark). A dash marks a check that cannot be computed because the benchmark stored, or discarded, no answers.}",
        "\\label{tab:validation-gate}", "\\end{table}",
    ]
    (ROOT / "defense/thesis_report/figures/auto/tab_validation_gate_locked.tex").write_text("\n".join(lines) + "\n")
    print(json.dumps({k: v for k, v in out.items() if k != "per_bench"}, indent=1))
    for b, r in P.items():
        print(b, {k: (round(v, 3) if isinstance(v, float) else v) for k, v in r.items()})


if __name__ == "__main__":
    main()

def ces():
    p = AUTO / "tab_ces_caem_trajectory.tex"
    s = p.read_text()
    for c in range(6):
        m = re.search(rf"^(\\rowcolor\{{gray!18\}}\n)?(\\textbf\{{)?C{c}(\}})?(\$\^\{{\\ast\}}\$)? & (.*)\\\\$", s, re.M)
        cells = [x.strip() for x in m.group(5).split("&")]
        num = lambda x: float(re.sub(r"[^0-9.]", "", x))
        ret, cal, ver = num(cells[2]), num(cells[3]), num(cells[4])
        acc, epi = J[f"caem_c{c}"]["pooled"]["em"], 1 - J[f"caem_c{c}"]["pooled"]["chm"]
        val = math.exp(sum(math.log(max(0.01, min(1.0, x))) for x in (acc, epi, ret, cal, ver)) / 5)
        keep = lambda x, v: x.replace(re.search(r"[0-9.]+", x).group(0), f"{v:.3f}")
        new = [keep(cells[0], acc), keep(cells[1], epi), cells[2], cells[3], cells[4], keep(cells[5], val)]
        s = s[:m.start(5)] + " & ".join(new) + " " + s[m.end(5):]
    tag = HEAD.replace("do not edit", "ACC/EPI/CES columns")
    s = s.replace(tag, "")
    p.write_text(s.replace("\\begin{table}", tag + "\\begin{table}", 1))



def ruc():
    rows = []
    tot = {"off": [], "on": []}
    for group, benches in (("Training panel", FS.TRAIN), ("Transfer panel", ("strategyqa", "truthfulqa"))):
        rows.append(f"\\multicolumn{{10}}{{@{{}}l}}{{\\textit{{{group}}}}} \\\\")
        for b in benches:
            off = eval_rows(FS.answer_path("phase1d_c3", b))
            on = eval_rows(FS.answer_path("caem_c3", b))
            tot["off"] += off
            tot["on"] += on
            t3 = lambda S: sum(s.get("tier") == 3 for s in S) / len(S)
            e_off, e_on = J["phase1d_c3"][b]["em"], J["caem_c3"][b]["em"]
            c_off, c_on = J["phase1d_c3"][b]["chm"], J["caem_c3"][b]["chm"]
            rows.append(f"{LONG[b]} & ${f3(e_off)}$ & ${f3(e_on)}$ & ${100 * (e_on - e_off):+.1f}$ & ${f3(c_off)}$ & "
                        f"${f3(c_on)}$ & ${100 * (c_on - c_off) / c_off:+.1f}\\%$ & ${pct(t3(off))}$ & ${pct(t3(on))}$ & "
                        f"${100 * (t3(on) - t3(off)):+.1f}$ \\\\")
        rows.append("\\midrule")
    t3 = lambda S: sum(s.get("tier") == 3 for s in S) / len(S)
    e_off, e_on = J["phase1d_c3"]["pooled"]["em"], J["caem_c3"]["pooled"]["em"]

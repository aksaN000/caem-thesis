def _pooled_cal_fold_band(csv_path):
    """Min/max of the pooled cal-fold pi_store column of tab_pi_store_trajectory.

    Reads outputs/full_run/pi_store_trajectory.csv (written by
    scripts/aggregate_pi_store_trajectory.py): rows with benchmark == "pooled"
    and source "cal_fold" (cycles >= 1) or "weight_validation" (cycle 0), the
    same cells the pi_store table prints. Values are rounded to 3 dp as in that
    table. Returns (lo, hi) or None when the CSV is missing or has no such rows.
    """
    import csv
    if not csv_path.is_file():
        return None
    vals = []
    with csv_path.open(newline='', encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r.get('benchmark') == 'pooled' and r.get('source') in ('cal_fold', 'weight_validation'):
                try:
                    vals.append(round(float(r['pi_store']), 3))
                except (KeyError, TypeError, ValueError):
                    continue
    if not vals:
        return None
    return min(vals), max(vals)



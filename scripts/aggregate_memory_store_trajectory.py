#!/usr/bin/env python
"""
scripts/aggregate_memory_store_trajectory.py
=============================================
Per-cycle memory store size + deferred-buffer size trajectory.

Empirical receipt for the H3-prime claim ("episodic memory accretes
across cycles") that isn't directly testable on the content-hash-disjoint
eval fold but IS observable on the memory store itself.

Inputs (read-only)
------------------
  outputs/full_run/memory_store_cycle_{N}.meta   (pickled list/dict; entry count)
  outputs/full_run/deferred_buffer_cycle_{N}.pkl (pickled list; deferred count)

Outputs
-------
  outputs/tab_memory_store_trajectory.csv
  thesis_report/figures/auto/tab_memory_store_trajectory.tex

Memory refs:
  caem_post_c5_metric_audit.md  -- this metric flagged as GAP
"""

from __future__ import annotations

import argparse
import csv
import logging
import pickle
import sys
from pathlib import Path
from typing import List, Optional, Tuple

logger = logging.getLogger(__name__)


def _count_entries(path: Path) -> Optional[int]:
    """Try to count entries in a pickled memory store meta or deferred buffer."""
    if not path.is_file():
        return None
    try:
        with path.open("rb") as fh:
            d = pickle.load(fh)
    except Exception as e:
        logger.warning("Could not unpickle %s: %s", path, e)
        return None
    if isinstance(d, list):
        return len(d)
    if isinstance(d, dict):
        # CAEM memory store .meta structure: {metadata: dict, next_id: int, dim: int, config: CAEMConfig}
        # Entry count lives in d["metadata"] (id → entry record dict).
        if "metadata" in d and hasattr(d["metadata"], "__len__"):
            return len(d["metadata"])
        # Deferred buffer pickles are bare lists OR dicts keyed by id
        for key in ("entries", "data", "items", "samples"):
            if key in d:
                v = d[key]
                if hasattr(v, "__len__"):
                    return len(v)
        return len(d)
    if hasattr(d, "__len__"):
        return len(d)
    return None


def collect(full_run_dir: Path, cycles: List[int]) -> List[Tuple[int, Optional[int], Optional[int]]]:
    rows = []
    for c in cycles:
        mem = _count_entries(full_run_dir / f"memory_store_cycle_{c}.meta")
        defr = _count_entries(full_run_dir / f"deferred_buffer_cycle_{c}.pkl")
        rows.append((c, mem, defr))
    return rows


def write_csv(rows, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["cycle", "memory_size", "deferred_buffer_size", "memory_delta"])
        prev_mem = None
        for c, mem, defr in rows:
            delta = (mem - prev_mem) if (mem is not None and prev_mem is not None) else ""
            w.writerow([c, mem if mem is not None else "",
                        defr if defr is not None else "", delta])
            prev_mem = mem if mem is not None else prev_mem
    logger.info("Wrote CSV: %s", path)


def write_latex(rows, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tex = []
    tex.append("% Auto-generated by scripts/aggregate_memory_store_trajectory.py")
    tex.append("\\begin{tabular}{cccc}")
    tex.append("\\toprule")
    tex.append("Cycle & Memory store size & Deferred buffer size & $\\Delta$ memory \\\\")
    tex.append("\\midrule")
    prev_mem = None
    for c, mem, defr in rows:
        if mem is None and defr is None:
            continue
        mem_s = str(mem) if mem is not None else "--"
        defr_s = str(defr) if defr is not None else "--"
        if mem is not None and prev_mem is not None:
            delta_s = f"$+{mem - prev_mem}$" if mem >= prev_mem else f"${mem - prev_mem}$"
        else:
            delta_s = "--"
        tex.append(f"C{c} & {mem_s} & {defr_s} & {delta_s} \\\\")
        if mem is not None:
            prev_mem = mem
    tex.append("\\bottomrule")
    tex.append("\\end{tabular}")
    tex.append("")
    tex.append("Per-cycle episodic-memory accretion. Deferred-buffer size shows entries waiting for re-verification.")
    path.write_text("\n".join(tex) + "\n")
    logger.info("Wrote LaTeX: %s", path)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--full_run_dir", type=Path,
                   default=Path("outputs/full_run"))
    p.add_argument("--cycles", type=int, nargs="+", default=[0, 1, 2, 3, 4, 5])
    p.add_argument("--out_csv", type=Path,
                   default=Path("outputs/tab_memory_store_trajectory.csv"))
    p.add_argument("--out_tex", type=Path,
                   default=Path("thesis_report/figures/auto/tab_memory_store_trajectory.tex"))
    p.add_argument("--log_level", default="INFO")
    ns = p.parse_args()
    logging.basicConfig(level=ns.log_level, format="%(asctime)s %(levelname)s %(message)s")

    rows = collect(ns.full_run_dir, ns.cycles)
    print(f"\n{'Cycle':<6} | {'Memory':>8} | {'Deferred':>9} | Δmemory")
    print("-" * 50)
    prev = None
    for c, mem, defr in rows:
        m = str(mem) if mem is not None else "--"
        d = str(defr) if defr is not None else "--"
        delta = f"+{mem - prev}" if (mem is not None and prev is not None) else "--"
        print(f"C{c:<5} | {m:>8} | {d:>9} | {delta}")
        if mem is not None: prev = mem

    write_csv(rows, ns.out_csv)
    write_latex(rows, ns.out_tex)
    return 0


if __name__ == "__main__":
    sys.exit(main())

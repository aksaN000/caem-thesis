"""Build the chapter-5 evidence tables added in the final drafting pass (2026-10).

Read-only on its inputs; writes three new LaTeX tables to
defense/thesis_report/figures/auto/ and one JSON record to outputs/analysis/.

Tables
------
tab_gate_quality.tex      Storage gate on the training-panel calibration fold, per cycle:
                          share stored, precision, TPR, FPR, balanced accuracy, Cohen's d,
                          and per-benchmark balanced accuracy. C0 comes from the re-run
                          sweep (locked variant, in-sample); C1-C5 from the per-cycle
                          calibration-fold scores written by the main run (STORE decision).
tab_sweep_variants.tex    Selected rows of the re-run cycle-zero sweep
                          (outputs/cycle_0/sweep_v2_1/variants.csv).
tab_headline_steps.tex    Three-step headline: B1, C0, C2, C5 on EM, CHM, the two
                          verifier-defined subtypes, coverage and error among answered.

Inputs
------
outputs/full_run/cycle_{1,2,3,5}/calibration/<bench>_cycle<N>.json
outputs/cycle_0/calibration/calibration_fold_samples.json (labels for C0)
outputs/cycle_0/sweep_v2_1/variants.csv
outputs/full_run/eval/<bench>_cycle<N>.json (evaluation fold, n = 300 per benchmark)
figures/auto/tab_halluc_subtypes.tex and tab_pooled_trajectory.tex are NOT read; the
B1 EM/CHM/subtype values are taken from outputs/tab_headline_decomposition.csv and
outputs/baselines (see B1_* constants, checked against the committed tables).
"""
import csv
import glob
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "defense/thesis_report/figures/auto"
TRAIN = ("fever", "triviaqa", "commonsense_qa")
PANEL = ("fever", "triviaqa", "commonsense_qa", "truthfulqa", "strategyqa")
NAME = {"fever": "FEVER", "triviaqa": "TriviaQA", "commonsense_qa": "CommonsenseQA"}


def em_of(s, bench):
    if bench == "truthfulqa" and s.get("em_llm_judged") is not None:
        return float(s["em_llm_judged"])
    return float(s.get("em") or 0.0)


def gate_stats(samples):
    pos = [s for s in samples if s["em"] >= 1]
    neg = [s for s in samples if s["em"] < 1]
    tp = sum(s["decision"] == "STORE" for s in pos)
    fp = sum(s["decision"] == "STORE" for s in neg)
    up = [s["u_stored"] for s in pos]
    un = [s["u_stored"] for s in neg]
    sd = ((st.pvariance(up) * len(up) + st.pvariance(un) * len(un)) / len(samples)) ** 0.5
    tpr, fpr = tp / len(pos), fp / len(neg)
    return {
        "n": len(samples), "stored": tp + fp, "share": (tp + fp) / len(samples),
        "precision": tp / (tp + fp) if tp + fp else None, "tpr": tpr, "fpr": fpr,
        "ba": (tpr + 1 - fpr) / 2, "d": (st.mean(up) - st.mean(un)) / sd,
    }


def c0_from_sweep():
    """C0 locked variant on the calibration fold (in-sample), from the re-run sweep."""
    rows = list(csv.DictReader(open(ROOT / "outputs/cycle_0/sweep_v2_1/variants.csv")))
    lock = next(r for r in rows if float(r["tau_store"]) == 0.60 and float(r["boost_C"]) == 0.01
                and float(r["alpha_shrink"]) == 0.6)
    d = json.load(open(ROOT / "outputs/cycle_0/calibration/calibration_fold_samples.json"))
    S = d["samples"]
    npos = sum(1 for s in S if s["em"] >= 1)
    nneg = len(S) - npos
    tp, stored = int(lock["cal_correct"]), int(lock["cal_stored"])
    tpr, fpr = tp / npos, (stored - tp) / nneg
    per = {}
    V = json.load(open(ROOT / "outputs/cycle_0/sweep_v2_1/variants.json"))
    V = V if isinstance(V, list) else V.get("variants", V)
    return {"n": len(S), "stored": stored, "share": stored / len(S), "precision": tp / stored,
            "tpr": tpr, "fpr": fpr, "ba": (tpr + 1 - fpr) / 2, "d": float(lock["cal_d_pooled"]),
            "ba_per_bench": per}


def gate_table():
    res = {0: c0_from_sweep()}
    for c in (1, 2, 3, 5):
        S, per = [], {}
        for b in TRAIN:
            s = json.load(open(ROOT / f"outputs/full_run/cycle_{c}/calibration/{b}_cycle{c}.json"))["samples"]
            S += s
            per[b] = gate_stats(s)["ba"]
        r = gate_stats(S)
        r["ba_per_bench"] = per
        res[c] = r
    lines = [
        "% Auto-generated by scripts/build_ch5_evidence_tables.py (final drafting pass, 2026-10).",
        "\\begin{table}[!htbp]", "\\centering\\small", "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lrrrrrrrrr@{}}", "\\toprule",
        " & \\multicolumn{6}{c}{\\textbf{Pooled training panel}} & \\multicolumn{3}{c}{\\textbf{Balanced accuracy}} \\\\",
        "\\cmidrule(lr){2-7}\\cmidrule(l){8-10}",
        "\\textbf{Cycle} & \\textbf{Stored} & \\textbf{Precision} & \\textbf{TPR} & \\textbf{FPR} & \\textbf{Bal.\\ acc.} & \\textbf{Cohen's $d$} & \\textbf{FEVER} & \\textbf{TriviaQA} & \\textbf{CSQA} \\\\",
        "\\midrule",
    ]
    for c, r in res.items():
        pb = r["ba_per_bench"]
        pbs = " & ".join(f"${pb[b]:.3f}$" if b in pb else "--" for b in TRAIN)
        tag = "C0$^{\\ast}$" if c == 0 else f"C{c}"
        lines.append(f"{tag} & ${r['stored']}$ ({100*r['share']:.1f}\\%) & ${r['precision']:.3f}$ & ${r['tpr']:.3f}$ & "
                     f"${r['fpr']:.3f}$ & ${r['ba']:.3f}$ & ${r['d']:.3f}$ & {pbs} \\\\")
    lines += [
        "\\bottomrule", "\\end{tabular}",
        "\\caption[Storage gate quality on the calibration fold by cycle.]{Storage gate quality on the training-panel calibration fold ($1{,}500$ questions) by cycle. $^{\\ast}$C0 is in-sample (the composite was fitted on this fold); C1 to C5 score the fold with the new adapter before the composite is refitted. C4 was rolled back and has no reading.}",
        "\\label{tab:gate-quality}", "\\end{table}",
    ]
    (OUT / "tab_gate_quality.tex").write_text("\n".join(lines) + "\n")
    return res


def sweep_table():
    rows = list(csv.DictReader(open(ROOT / "outputs/cycle_0/sweep_v2_1/variants.csv")))
    pick = []
    for r in rows:
        t, C, a = float(r["tau_store"]), float(r["boost_C"]), float(r["alpha_shrink"])
        if C == 0.01 and t == 0.60:
            pick.append(r)
        elif C == 0.01 and a == 0.6 and t in (0.55, 0.65, 0.70):
            pick.append(r)
        elif C == 1.0 and t == 0.60 and a == 0.6:
            pick.append(r)
    pick.sort(key=lambda r: (float(r["boost_C"]), float(r["tau_store"]), float(r["alpha_shrink"])))
    lines = [
        "% Auto-generated by scripts/build_ch5_evidence_tables.py from outputs/cycle_0/sweep_v2_1/variants.csv.",
        "\\begin{table}[!htbp]", "\\centering\\small", "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}rrrrrrrrrc@{}}", "\\toprule",
        " & & & \\multicolumn{3}{c}{\\textbf{Calibration fold}} & \\multicolumn{3}{c}{\\textbf{Validation fold}} & \\\\",
        "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}",
        "$\\tau_{\\text{store}}$ & $C$ & $\\alpha_{\\text{shrink}}$ & $d$ & Stored & Precision & $d$ & Stored & Precision & Criteria 1--2 \\\\",
        "\\midrule",
    ]
    for r in pick:
        locked = float(r["tau_store"]) == 0.60 and float(r["boost_C"]) == 0.01 and float(r["alpha_shrink"]) == 0.6
        ok = "yes" if r["pass_c1_d"] == "True" and r["pass_c2_nmin"] == "True" else "no"
        cells = (f"${float(r['tau_store']):.2f}$ & ${float(r['boost_C']):g}$ & ${float(r['alpha_shrink']):.1f}$ & "
                 f"${float(r['cal_d_pooled']):.2f}$ & ${int(r['cal_stored'])}$ & ${float(r['cal_precision']):.3f}$ & "
                 f"${float(r['val_d_pooled']):.2f}$ & ${int(r['val_stored'])}$ & ${float(r['val_precision']):.3f}$ & {ok}")
        if locked:
            cells = "\\rowcolor{gray!18} " + cells
        lines.append(cells + " \\\\")
    lines += [
        "\\bottomrule", "\\end{tabular}",
        "\\caption[Selected variants of the cycle-zero sweep.]{Selected variants of the $100$-variant cycle-zero sweep (re-run with the locked code; shaded: locked configuration). Calibration fold and held-out validation fold have $500$ questions per training benchmark.}",
        "\\label{tab:sweep-variants}", "\\end{table}",
    ]
    (OUT / "tab_sweep_variants.tex").write_text("\n".join(lines) + "\n")


def eval_view(c):
    n = ans = wrong_ans = 0
    for b in PANEL:
        for s in json.load(open(ROOT / f"outputs/full_run/eval/{b}_cycle{c}.json"))["samples"]:
            n += 1
            if s.get("decision") != "ABSTAIN":
                ans += 1
                wrong_ans += em_of(s, b) < 1
    return ans / n, wrong_ans / ans


# B1 reference values as committed in tab_pooled_trajectory / tab_halluc_subtypes (zero-shot, n = 300 per benchmark).
B1 = {"em": 0.507, "chm": 0.120, "confab": 0.268, "refusal": 0.060, "coverage": 1.0}
CAEM = {  # committed tab_pooled_trajectory / tab_halluc_subtypes values
    0: {"em": 0.541, "chm": 0.135, "confab": 0.087, "refusal": 0.305},
    2: {"em": 0.544, "chm": 0.107, "confab": 0.239, "refusal": 0.057},
    5: {"em": 0.517, "chm": 0.109, "confab": 0.269, "refusal": 0.064},
}


def headline_table():
    rows = [("B1 (zero-shot)", B1["em"], B1["chm"], B1["confab"], B1["refusal"], 1.0, 1 - B1["em"])]
    for c in (0, 2, 5):
        cov, err = eval_view(c)
        v = CAEM[c]
        rows.append((f"CAEM C{c}", v["em"], v["chm"], v["confab"], v["refusal"], cov, err))
    lines = [
        "% Auto-generated by scripts/build_ch5_evidence_tables.py; EM/CHM/subtypes as committed in",
        "% tab_pooled_trajectory and tab_halluc_subtypes; coverage and error-among-answered from the",
        "% per-sample evaluation files (ABSTAIN = not answered; TruthfulQA uses the judged correctness field).",
        "\\begin{table}[!htbp]", "\\centering\\small", "\\setlength{\\tabcolsep}{5pt}",
        "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
        "\\textbf{System} & \\textbf{EM} & \\textbf{CHM} & \\textbf{Conf.\\ confab.} & \\textbf{False refusal} & \\textbf{Answered} & \\textbf{Wrong among answered} \\\\",
        "\\midrule",
    ]
    for name, em, chm, cf, fr, cov, err in rows:
        lines.append(f"{name} & ${em:.3f}$ & ${chm:.3f}$ & ${cf:.3f}$ & ${fr:.3f}$ & ${100*cov:.1f}\\%$ & ${err:.3f}$ \\\\")
    lines += [
        "\\bottomrule", "\\end{tabular}",
        "\\caption[The headline in three steps.]{The headline in three steps on the five-benchmark evaluation fold ($1{,}500$ questions). B1 to C0 isolates the architecture, C0 to C5 the self-improvement loop, B1 to C5 the whole system.}",
        "\\label{tab:headline-steps}", "\\end{table}",
    ]
    (OUT / "tab_headline_steps.tex").write_text("\n".join(lines) + "\n")
    return rows


if __name__ == "__main__":
    g = gate_table()
    sweep_table()
    h = headline_table()
    (ROOT / "outputs/analysis").mkdir(parents=True, exist_ok=True)
    json.dump({"gate_quality": {str(k): v for k, v in g.items()}, "headline_steps": h},
              open(ROOT / "outputs/analysis/ch5_evidence_tables.json", "w"), indent=2, default=float)
    print("ok")
